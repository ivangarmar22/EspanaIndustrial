const httpsUrl = (v: string | undefined, hosts: RegExp) => {
  try {
    const u = new URL(v ?? "");
    return u.protocol === "https:" && hosts.test(u.hostname) ? u.toString() : undefined;
  } catch {
    return undefined;
  }
};

