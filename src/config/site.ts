/** Address the site is built for: NEXT_PUBLIC_SITE_URL, with an "ñ" domain in its ASCII (punycode) form. */
const siteUrl = () => {
  const u = new URL(process.env.NEXT_PUBLIC_SITE_URL || "http://127.0.0.1:3000");
  return `${u.origin}${u.pathname}`.replace(/\/$/, "");
};

